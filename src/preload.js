'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getMeta: () => ipcRenderer.invoke('app:getMeta'),
  getConfig: () => ipcRenderer.invoke('config:get'),
  saveConfig: (c) => ipcRenderer.invoke('config:save', c),
  getInstances: () => ipcRenderer.invoke('instances:get'),
  start: () => ipcRenderer.invoke('modbus:start'),
  getState: () => ipcRenderer.invoke('modbus:state'),
  isRunning: () => ipcRenderer.invoke('modbus:isRunning'),
  stop: () => ipcRenderer.invoke('modbus:stop'),
  pollNow: () => ipcRenderer.invoke('modbus:pollNow'),
  getSamples: () => ipcRenderer.invoke('samples:get'),
  clearSamples: () => ipcRenderer.invoke('samples:clear'),
  exportCsv: () => ipcRenderer.invoke('csv:export'),
  startLog: () => ipcRenderer.invoke('log:start'),
  stopLog: () => ipcRenderer.invoke('log:stop'),
  logStatus: () => ipcRenderer.invoke('log:status'),
  historyStatus: () => ipcRenderer.invoke('history:status'),
  historyRoots: () => ipcRenderer.invoke('history:roots'),
  historyFolderInfo: (f) => ipcRenderer.invoke('history:folderInfo', f),
  historyLoad: () => ipcRenderer.invoke('history:load'),
  historyOpenFolder: () => ipcRenderer.invoke('history:openFolder'),
  historyChooseFolder: () => ipcRenderer.invoke('history:chooseFolder'),
  onHistoryStatus: (cb) => ipcRenderer.on('history:status', (_e, s) => cb(s)),
  detectModules: (opts) => ipcRenderer.invoke('modules:detect', opts),
  onDetectProgress: (cb) => ipcRenderer.on('modules:progress', (_e, p) => cb(p)),
  discoverySubnets: () => ipcRenderer.invoke('discovery:subnets'),
  discoveryStart: (opts) => ipcRenderer.invoke('discovery:start', opts),
  discoveryCancel: () => ipcRenderer.invoke('discovery:cancel'),
  onDiscoveryProgress: (cb) => ipcRenderer.on('discovery:progress', (_e, p) => cb(p)),
  onDiscoveryFound: (cb) => ipcRenderer.on('discovery:found', (_e, r) => cb(r)),
  onData: (cb) => ipcRenderer.on('modbus:data', (_e, d) => cb(d)),
  onStatus: (cb) => ipcRenderer.on('modbus:status', (_e, s) => cb(s)),
  onRunning: (cb) => ipcRenderer.on('modbus:running', (_e, r) => cb(r)),
  getBackground: () => ipcRenderer.invoke('background:get'),
  onConfigChanged: (cb) => ipcRenderer.on('config:changed', (_e, c) => cb(c)),
});
